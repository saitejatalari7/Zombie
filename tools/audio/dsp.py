"""Small DSP kit for the game's synthesized audio (numpy + scipy). Everything the game
plays is generated by tools/audio/*.py, so it is ours outright: no licence, no credit."""
import os
import subprocess
import tempfile

import numpy as np
from scipy import signal
from scipy.io import wavfile

SR = 44100
rng = np.random.default_rng(7)


def t(dur):
    return np.arange(int(dur * SR)) / SR


def noise(dur):
    return rng.uniform(-1.0, 1.0, int(dur * SR))


def env_exp(dur, decay, attack=0.002):
    x = t(dur)
    e = np.exp(-x / max(decay, 1e-4))
    if attack > 0:
        e *= np.clip(x / attack, 0.0, 1.0)
    return e


def env_adsr(dur, a, d, s, r):
    n = int(dur * SR)
    e = np.zeros(n)
    ai, di, ri = int(a * SR), int(d * SR), int(r * SR)
    si = max(n - ai - di - ri, 0)
    seg = [np.linspace(0, 1, ai, endpoint=False), np.linspace(1, s, di, endpoint=False),
           np.full(si, s), np.linspace(s, 0, ri)]
    c = np.concatenate(seg)[:n]
    e[:len(c)] = c
    return e


def _sos(kind, f, order=2):
    if kind == "bp":
        lo, hi = f
        return signal.butter(order, [max(lo, 20) / (SR / 2), min(hi, SR / 2 - 100) / (SR / 2)], btype="band", output="sos")
    return signal.butter(order, min(max(f, 20), SR / 2 - 100) / (SR / 2), btype=kind, output="sos")


def lp(x, f, order=2):
    return signal.sosfilt(_sos("low", f, order), x)


def hp(x, f, order=2):
    return signal.sosfilt(_sos("high", f, order), x)


def bp(x, lo, hi, order=2):
    return signal.sosfilt(_sos("bp", (lo, hi), order), x)


def sweep_filter(x, f0, f1, kind="low", steps=24):
    """Time-varying filter by blocks (cutoff glides from f0 to f1)."""
    out = np.zeros_like(x)
    edges = np.linspace(0, len(x), steps + 1).astype(int)
    for k in range(steps):
        f = f0 * (f1 / f0) ** (k / max(steps - 1, 1))
        seg = x[max(edges[k] - 512, 0):edges[k + 1]]
        y = signal.sosfilt(_sos(kind, f), seg)
        out[edges[k]:edges[k + 1]] = y[-(edges[k + 1] - edges[k]):]
    return out


def osc(freq, dur, shape="sine", phase=0.0):
    """freq: number or array (Hz per sample)."""
    n = int(dur * SR)
    f = np.full(n, float(freq)) if np.isscalar(freq) else np.asarray(freq)[:n]
    ph = phase + 2 * np.pi * np.cumsum(f) / SR
    if shape == "sine":
        return np.sin(ph)
    if shape == "saw":
        return 2.0 * ((ph / (2 * np.pi)) % 1.0) - 1.0
    if shape == "square":
        return np.sign(np.sin(ph))
    if shape == "tri":
        return 2.0 * np.abs(2.0 * ((ph / (2 * np.pi)) % 1.0) - 1.0) - 1.0
    raise ValueError(shape)


def glide(f0, f1, dur, curve=1.0):
    x = np.linspace(0, 1, int(dur * SR)) ** curve
    return f0 * (f1 / f0) ** x


def drive(x, amount):
    return np.tanh(x * amount) / np.tanh(amount)


def formants(src, peaks, q=6.0):
    """Vowel colour: sum of band-passes around formant frequencies (f, gain)."""
    out = np.zeros_like(src)
    for f, g in peaks:
        bw = f / q
        out += g * bp(src, f - bw, f + bw)
    return out


def reverb(x, seconds=1.2, mix=0.25, damp=3500.0, pre=0.012):
    n = int(seconds * SR)
    ir = rng.uniform(-1, 1, n) * np.exp(-np.arange(n) / (SR * seconds / 6.0))
    ir = lp(ir, damp)
    ir[:int(pre * SR)] = 0
    ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
    wet = signal.fftconvolve(x, ir)
    dry = np.zeros(len(wet))
    dry[:len(x)] = x
    return dry * (1 - mix) + wet * mix


def place(buf, clip, at, gain=1.0):
    i = int(at * SR)
    j = min(len(buf), i + len(clip))
    if j > i:
        buf[i:j] += clip[:j - i] * gain
    return buf


def fade(x, fin=0.002, fout=0.02):
    x = x.copy()
    a, b = int(fin * SR), int(fout * SR)
    if a:
        x[:a] *= np.linspace(0, 1, a)
    if b:
        x[-b:] *= np.linspace(1, 0, b)
    return x


def normalize(x, peak=0.89):
    m = np.max(np.abs(x)) + 1e-9
    return x * (peak / m)


def trim(x, thresh=1e-4):
    idx = np.where(np.abs(x) > thresh)[0]
    return x[:idx[-1] + 1] if len(idx) else x


def write_ogg(path, x, quality=4, peak=0.89, do_trim=True):
    """x: mono (n,) or stereo (n, 2). Normalized, faded, written as Ogg Vorbis."""
    if x.ndim == 1:
        if do_trim:
            x = trim(x)
        x = fade(normalize(x, peak), 0.0005, 0.01)
    else:
        x = x / (np.max(np.abs(x)) + 1e-9) * peak
    pcm = (np.clip(x, -1, 1) * 32767).astype(np.int16)
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        wavfile.write(tmp.name, SR, pcm)
        tmp_path = tmp.name
    os.makedirs(os.path.dirname(path), exist_ok=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp_path, "-c:a", "libvorbis",
                    "-q:a", str(quality), path], check=True)
    os.remove(tmp_path)
